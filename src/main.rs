//! `pie`: run the simulation and evaluation, write reports, replay into Postgres, serve the API.

use anyhow::{Context, Result, anyhow, bail};
use stablecoin_payin_engine::{api, config, eval, report, sim, store};
use std::path::PathBuf;

const DEV_SEEDS: &[u64] = &[11, 12, 13];

fn root() -> PathBuf {
    config::repo_root()
}

fn arg(args: &[String], flag: &str) -> Option<String> {
    args.iter().position(|a| a == flag).and_then(|i| args.get(i + 1).cloned())
}

fn world(name: &str, seed: Option<u64>) -> Result<sim::world::World> {
    let mut wc = sim::world::WorldCfg::load(name)?;
    if let Some(s) = seed {
        wc.seed = s;
    }
    Ok(sim::world::generate(&wc))
}

fn evaluate() -> Result<()> {
    let mut runs = vec![];
    let mut bench = vec![];
    for &seed in DEV_SEEDS {
        let w = world("world", Some(seed))?;
        let e = eval::evaluate(&sim::run::run(&w, config::load_named("engine")?, false), "dev", seed);
        let b = eval::evaluate(&sim::run::run(&w, config::load_named("baseline")?, false), "dev", seed);
        eprintln!(
            "dev seed {seed}: engine {}/{} correct, baseline {}/{}",
            e.correct_outcome.hit, e.correct_outcome.of, b.correct_outcome.hit, b.correct_outcome.of
        );
        bench.push(serde_json::json!({"seed": seed, "engine_ms": e.engine_ms, "inputs": e.inputs, "inputs_per_sec": e.inputs_per_sec}));
        let mut ev = serde_json::to_value(&e)?;
        let mut bv = serde_json::to_value(&b)?;
        // Timings vary from machine to machine; they go to bench.json so results.json is reproducible.
        for v in [&mut ev, &mut bv] {
            let m = v.as_object_mut().unwrap();
            m.remove("engine_ms");
            m.remove("inputs_per_sec");
        }
        runs.push(serde_json::json!({"seed": seed, "engine": ev, "baseline": bv}));
    }
    std::fs::create_dir_all(root().join("reports"))?;
    std::fs::write(
        root().join("reports/bench.json"),
        serde_json::to_string_pretty(&serde_json::json!({"about": "Engine time in memory per dev world, one core. Varies by machine.", "runs": bench}))? + "\n",
    )?;
    let out = serde_json::json!({
        "about": "Generated by `pie evaluate`. Do not edit by hand.",
        "world_config_sha256": store::sha256_hex(std::fs::read(root().join("config/world.json"))?.as_slice()),
        "engine_config_sha256": store::sha256_hex(std::fs::read(root().join("config/engine.json"))?.as_slice()),
        "dev": runs,
    });
    std::fs::create_dir_all(root().join("reports"))?;
    std::fs::write(root().join("reports/results.json"), serde_json::to_string_pretty(&out)? + "\n")?;
    eprintln!("wrote reports/results.json");
    Ok(())
}

fn heldout(rerun: bool) -> Result<()> {
    let pin = std::fs::read_to_string(root().join("eval/heldout/v1.sha256"))?;
    let want = pin.split_whitespace().next().unwrap_or_default().to_string();
    let got = store::sha256_hex(&std::fs::read(root().join("config/world_heldout.json"))?);
    if want != got {
        bail!("config/world_heldout.json does not match its pin in eval/heldout/v1.sha256; the held-out world must not change");
    }
    let dir = root().join("reports/heldout/v1");
    std::fs::create_dir_all(&dir)?;
    let first = dir.join("first_run.json");
    if first.exists() && !rerun {
        bail!("the first held-out run is already recorded in {}; use --rerun to write latest.json instead", first.display());
    }
    let w = world("world_heldout", None)?;
    let e = eval::evaluate(&sim::run::run(&w, config::load_named("engine")?, false), "heldout-v1", w.cfg.seed);
    let b = eval::evaluate(&sim::run::run(&w, config::load_named("baseline")?, false), "heldout-v1", w.cfg.seed);
    let commit = std::process::Command::new("git")
        .args(["rev-parse", "--short", "HEAD"])
        .current_dir(root())
        .output()
        .ok()
        .map(|o| String::from_utf8_lossy(&o.stdout).trim().to_string())
        .unwrap_or_default();
    let v = serde_json::json!({"set": "v1", "commit": commit, "world_sha256": got, "engine": e, "baseline": b});
    let target = if first.exists() { dir.join("latest.json") } else { first.clone() };
    std::fs::write(&target, serde_json::to_string_pretty(&v)? + "\n")?;
    if target == first {
        std::fs::write(dir.join("first_run.sha256"), format!("{}  first_run.json\n", store::sha256_hex(&std::fs::read(&first)?)))?;
    }
    eprintln!(
        "held-out v1: engine {}/{} correct ({} misrouted), baseline {}/{}; wrote {}",
        e.correct_outcome.hit,
        e.correct_outcome.of,
        e.misrouted.n,
        b.correct_outcome.hit,
        b.correct_outcome.of,
        target.display()
    );
    Ok(())
}

async fn replay_pg(url: &str) -> Result<()> {
    let w = world("world", Some(DEV_SEEDS[0]))?;
    let out = sim::run::run(&w, config::load_named("engine")?, true);
    let mut pg = store::PgStore::connect(url).await?;
    pg.reset().await?;
    // Re-run the recorded inputs through a fresh engine, writing each input with its journals.
    let mut e = stablecoin_payin_engine::engine::Engine::new(config::load_named("engine")?, w.platform.clone());
    let started = std::time::Instant::now();
    let mut batch = vec![];
    let mut written = 0usize;
    for (at, input) in &out.inputs {
        let before = e.state.ledger.journals.len();
        e.handle(*at, input.clone())?;
        e.drain();
        batch.push((*at, input.clone(), e.state.ledger.journals[before..].to_vec()));
        if batch.len() >= 2000 {
            written += batch.len();
            pg.record_batch(&batch).await?;
            batch.clear();
        }
    }
    written += batch.len();
    pg.record_batch(&batch).await?;
    let secs = started.elapsed().as_secs_f64();
    // Same ledger three ways: the simulation's engine, the database, and an engine rebuilt from the database.
    let db = pg.balances().await?;
    let mut rebuilt = stablecoin_payin_engine::engine::Engine::new(config::load_named("engine")?, w.platform.clone());
    for (at, input) in pg.events().await? {
        rebuilt.handle(at, input)?;
        rebuilt.drain();
    }
    let mut mismatches = 0;
    for ((acct, ccy), v) in out.engine.state.ledger.balances() {
        let d = db.get(&(acct.clone(), ccy.code().to_string())).copied().unwrap_or(0);
        let r = rebuilt.state.ledger.balance(acct, *ccy);
        if d != *v || r != *v {
            mismatches += 1;
            eprintln!("mismatch {acct} {ccy}: engine {v} db {d} rebuilt {r}");
        }
    }
    let journals: i64 = pg.client.query_one("select count(*) from journals", &[]).await?.get(0);
    let postings: i64 = pg.client.query_one("select count(*) from postings", &[]).await?.get(0);
    let v = serde_json::json!({
        "about": "Generated by `pie replay-pg`: the dev world (seed 11) written to Postgres input by input, then rebuilt from the event log.",
        "events": written,
        "journals": journals,
        "postings": postings,
        "accounts": db.len(),
        "balance_mismatches": mismatches,
        "seconds": (secs * 10.0).round() / 10.0,
        "events_per_second": (written as f64 / secs).round(),
        "rebuilt_deposits_equal": rebuilt.state.deposits.len() == out.engine.state.deposits.len(),
    });
    std::fs::write(root().join("reports/replay_pg.json"), serde_json::to_string_pretty(&v)? + "\n")?;
    eprintln!("{v}");
    if mismatches > 0 {
        bail!("{mismatches} balances differ");
    }
    Ok(())
}

async fn serve(url: &str, addr: &str) -> Result<()> {
    let w = world("world", Some(DEV_SEEDS[0]))?;
    let service = api::Service::start(url, config::load_named("engine")?, w.platform.clone()).await?;
    let idem = store::PgStore::connect(url).await?;
    let state = std::sync::Arc::new(api::AppState { service: tokio::sync::Mutex::new(service), idem });
    let listener = tokio::net::TcpListener::bind(addr).await.with_context(|| format!("binding {addr}"))?;
    eprintln!("listening on http://{addr}");
    axum::serve(listener, api::router(state)).await?;
    Ok(())
}

/// Write a day of the dev world's bank files and the platform, for trying the API by hand.
fn sample_files(out: &str) -> Result<()> {
    let w = world("world", Some(DEV_SEEDS[0]))?;
    let dir = root().join(out);
    std::fs::create_dir_all(&dir)?;
    std::fs::write(dir.join("platform.json"), serde_json::to_string_pretty(&w.platform)?)?;
    let o = sim::run::run(&w, config::load_named("engine")?, true);
    let mut n = 0;
    for (_, input) in o.inputs.iter() {
        if let stablecoin_payin_engine::engine::Input::BankFile { name, raw } = input {
            std::fs::write(dir.join(name), raw)?;
            n += 1;
            if n >= 40 {
                break;
            }
        }
    }
    eprintln!("wrote {n} bank files and platform.json to {}", dir.display());
    Ok(())
}

fn usage() -> Result<()> {
    Err(anyhow!(
        "usage: pie <command>\n  evaluate              run the dev worlds with the engine and the baseline, write reports/results.json\n  heldout [--rerun]     run the pinned held-out world once (first_run.json), or again (latest.json)\n  report                write reports/REPORT.md and reports/dashboard.html\n  replay-pg --db URL    write the dev world to Postgres and rebuild the engine from it\n  serve --db URL [--addr 127.0.0.1:8080]\n  sample-files [--out data/sample]"
    ))
}

#[tokio::main]
async fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().collect();
    match args.get(1).map(String::as_str) {
        Some("evaluate") => evaluate(),
        Some("heldout") => heldout(args.iter().any(|a| a == "--rerun")),
        Some("report") => report::write_all(&root()),
        Some("replay-pg") => replay_pg(&arg(&args, "--db").ok_or_else(|| anyhow!("--db URL"))?).await,
        Some("serve") => serve(&arg(&args, "--db").ok_or_else(|| anyhow!("--db URL"))?, &arg(&args, "--addr").unwrap_or_else(|| "127.0.0.1:8080".into())).await,
        Some("sample-files") => sample_files(&arg(&args, "--out").unwrap_or_else(|| "data/sample".into())),
        _ => usage(),
    }
}
